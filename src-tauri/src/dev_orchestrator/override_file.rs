//! Generate the per-worktree compose file that turns a worktree's django into
//! a dev server on the shared infra. Each worktree gets a unique compose project
//! name (so containers don't collide), a unique django container name, and a
//! `command:` that binds django to the worktree's `BE_PORT`.
//!
//! It is deliberately **not** `docker-compose.override.yml`. Compose loads that
//! name on every command, so it would also rewire the throwaway
//! `docker compose run --rm django pytest` containers agents use for tests,
//! which rely on the checkout's own isolated postgres. Only the BE dev-server
//! command names this file (`-f`), so nothing else sees it.
//!
//! What the file has to carry, and why the BE is broken without each piece:
//!
//! - **The main stack's network.** Postgres and redis are deactivated here
//!   (`profiles: ["inactive"]`) and run only in the main stack, which publishes
//!   nothing on the host. Joining its compose network is what makes them
//!   reachable, at the same service names (`postgres`, `redis`, `mailhog`) the
//!   base file already points django at — so no env override is needed.
//! - **`ports: !override`** — the base file publishes 8000, which the main
//!   stack's django holds. Compose merges port lists rather than replacing
//!   them, so the worktree port has to replace it explicitly.
//! - **`depends_on: !reset []`** — a `depends_on` naming a deactivated service
//!   makes the whole project invalid.
//! - **Migrations before the server** — the shared database is only ever as
//!   migrated as whichever checkout last migrated it, so a worktree ahead of it
//!   fails on its first query against a missing table or column.

use std::fs;
use std::path::{Path, PathBuf};

use super::config::OrchestratorConfig;

/// The file Tethys writes into a worktree's BE dir.
pub const FILE_NAME: &str = "docker-compose.tethys.yml";

/// Where earlier versions wrote it. Removed on sight when Tethys generated it,
/// since Compose would otherwise keep auto-loading it.
const LEGACY_FILE_NAME: &str = "docker-compose.override.yml";

const HEADER: &str = "# Generated by Tethys dev orchestrator";

/// Path to the generated compose file inside a worktree's BE dir.
pub fn override_path(be_dir: &Path) -> PathBuf {
    be_dir.join(FILE_NAME)
}

/// Remove a `docker-compose.override.yml` an earlier Tethys wrote. A file that
/// doesn't carry the Tethys header is someone's own and is left alone.
pub fn remove_legacy(be_dir: &Path) -> bool {
    let legacy = be_dir.join(LEGACY_FILE_NAME);
    let ours = fs::read_to_string(&legacy)
        .map(|s| s.starts_with(HEADER))
        .unwrap_or(false);
    ours && fs::remove_file(&legacy).is_ok()
}

/// Write the compose file. Idempotent — overwrites whatever's there.
pub fn write(
    cfg: &OrchestratorConfig,
    be_dir: &Path,
    short: &str,
    be_port: u16,
) -> std::io::Result<()> {
    remove_legacy(be_dir);
    let project = cfg.compose_project(short);
    let container = cfg.be_container(short);
    let network = &cfg.main_stack_network;
    let script = cfg
        .be_startup_script
        .replace("{port}", &be_port.to_string())
        .replace('\\', "\\\\")
        .replace('"', "\\\"");
    let mut out = String::new();
    out.push_str(&format!(
        r#"{HEADER} — do not commit.
#
# Per-worktree django on the main stack's postgres/redis: the services marked
# profiles: [inactive] don't start here, and django joins the main stack's
# network ({network}) to reach them by their usual service names.
#
# Used only by Tethys's BE command (`docker compose -f docker-compose.yml
# -f {FILE_NAME} up`), so `docker compose run` for tests is unaffected.
#
# To bring this worktree's django down: docker compose -p {project} down
name: {project}
services:
  django:
    container_name: {container}
    command: ["sh", "-c", "{script}"]
    networks: [main_stack]
    ports: !override ["{be_port}:{be_port}"]
    depends_on: !reset []
"#
    ));
    if !cfg.bind_mounts.is_empty() {
        out.push_str("    volumes:\n");
        for bm in &cfg.bind_mounts {
            out.push_str(&format!(
                "      - {}:{}:ro\n",
                bm.host_path.display(),
                bm.container_path
            ));
        }
    }
    for svc in &cfg.inactive_services {
        out.push_str(&format!("  {svc}:\n    profiles: [\"inactive\"]\n"));
    }
    out.push_str(&format!(
        "networks:\n  main_stack:\n    name: {network}\n    external: true\n"
    ));
    fs::write(override_path(be_dir), out)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::dev_orchestrator::config::OrchestratorConfig;

    fn generated(be_port: u16) -> String {
        let tmp = tempfile::tempdir().unwrap();
        write(
            &OrchestratorConfig::newlantern(),
            tmp.path(),
            "9700",
            be_port,
        )
        .unwrap();
        std::fs::read_to_string(override_path(tmp.path())).unwrap()
    }

    fn django_block(out: &str) -> &str {
        let rest = out
            .split("  django:\n")
            .nth(1)
            .expect("the file always has a django block");
        // The block runs until the next service, whose key sits at two spaces.
        let end = rest
            .match_indices("\n  ")
            .find(|(i, _)| !rest[i + 3..].starts_with(' '))
            .map_or(rest.len(), |(i, _)| i);
        &rest[..end]
    }

    /// Regression: without this, `docker compose up` exits immediately with
    /// "service django depends on undefined service postgres" — so no container
    /// and no session ever appear, while Tethys still reports a started BE
    /// because it only ever spawned the command.
    #[test]
    fn the_django_block_clears_its_inherited_depends_on() {
        assert!(django_block(&generated(8003)).contains("depends_on: !reset []"));
    }

    /// The main stack publishes nothing on the host, so its network is the
    /// only way to its postgres and redis — and it has to be declared external,
    /// or Compose creates an empty network of the same name for this project.
    #[test]
    fn django_joins_the_main_stacks_network_rather_than_the_host() {
        let out = generated(8003);
        let cfg = OrchestratorConfig::newlantern();
        assert!(django_block(&out).contains("networks: [main_stack]"));
        assert!(out.contains(&format!(
            "networks:\n  main_stack:\n    name: {}\n    external: true\n",
            cfg.main_stack_network
        )));
        assert!(!out.contains("network_mode"), "got: {out}");
    }

    /// The base file publishes 8000, which the main stack's django holds;
    /// merged rather than replaced, the worktree would fail to bind it.
    #[test]
    fn the_worktree_port_replaces_the_base_files_port() {
        let out = generated(8003);
        let django = django_block(&out);
        assert!(
            django.contains(r#"ports: !override ["8003:8003"]"#),
            "got: {django}"
        );
    }

    #[test]
    fn the_server_starts_after_migrating_on_the_worktree_port() {
        let out = generated(8003);
        let django = django_block(&out);
        let migrate = django.find("migrate --noinput").expect("migrates");
        let serve = django.find("runserver_plus 0.0.0.0:8003").expect("serves");
        assert!(migrate < serve, "got: {django}");
    }

    #[test]
    fn deactivated_services_and_the_reset_travel_together() {
        let out = generated(8003);
        for svc in &OrchestratorConfig::newlantern().inactive_services {
            assert!(
                out.contains(&format!("  {svc}:\n    profiles: [\"inactive\"]")),
                "{svc} should be deactivated"
            );
        }
        assert!(out.contains("depends_on: !reset []"));
    }

    #[test]
    fn the_container_and_project_names_reach_the_file() {
        let out = generated(8003);
        let cfg = OrchestratorConfig::newlantern();
        assert!(out.contains(&cfg.be_container("9700")));
        assert!(out.contains(&format!("name: {}", cfg.compose_project("9700"))));
    }

    /// Compose auto-loads `docker-compose.override.yml`, so one left behind by
    /// an earlier Tethys would keep rewiring every `docker compose run` in the
    /// worktree. A hand-written one is not ours to delete.
    #[test]
    fn only_a_tethys_written_legacy_override_is_removed() {
        let tmp = tempfile::tempdir().unwrap();
        let legacy = tmp.path().join(LEGACY_FILE_NAME);

        std::fs::write(&legacy, format!("{HEADER} — do not commit.\n")).unwrap();
        write(&OrchestratorConfig::newlantern(), tmp.path(), "9700", 8003).unwrap();
        assert!(!legacy.exists());

        std::fs::write(&legacy, "services: {}\n").unwrap();
        write(&OrchestratorConfig::newlantern(), tmp.path(), "9700", 8003).unwrap();
        assert!(legacy.exists());
    }

    /// Writes the file beside a copy of the real backend compose file and asks
    /// docker to parse the pair the way the BE command does. Ignored by default
    /// (needs docker, a checkout, and the main stack's network to exist), but it
    /// is the only check that proves the file actually works.
    #[test]
    #[ignore]
    fn docker_accepts_the_generated_file() {
        let base = std::path::PathBuf::from(
            std::env::var("TETHYS_TEST_BE_DIR").expect("set TETHYS_TEST_BE_DIR"),
        );
        let tmp = tempfile::tempdir().unwrap();
        for f in ["docker-compose.yml", ".env", ".env.shared"] {
            let src = base.join(f);
            if src.exists() {
                std::fs::copy(&src, tmp.path().join(f)).unwrap();
            }
        }
        write(&OrchestratorConfig::newlantern(), tmp.path(), "test", 8099).unwrap();
        let out = std::process::Command::new("docker")
            .args(["compose", "-f", "docker-compose.yml", "-f", FILE_NAME])
            .args(["config", "--quiet"])
            .current_dir(tmp.path())
            .output()
            .expect("docker must run");
        assert!(
            out.status.success(),
            "compose rejected the generated file: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
}
